create policy "visits_select_own"
  on public.visits for select
  using (
    host_user_id in (select id from public.users where auth_uid = auth.uid())
    or visitor_eidolon_id in (
      select e.id from public.eidolons e
      join public.users u on u.id = e.user_id
      where u.auth_uid = auth.uid()
    )
  );

create policy "visits_service_all"  on public.visits for all using (auth.role() = 'service_role');
create policy "guilds_select_all"   on public.guilds for select using (true);
create policy "guilds_service_all"  on public.guilds for all using (auth.role() = 'service_role');
create policy "guild_members_select_all" on public.guild_members for select using (true);
create policy "guild_members_service_all" on public.guild_members for all using (auth.role() = 'service_role');
